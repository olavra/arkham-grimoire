/* Pack art, the texture behind each pack tile.

   GENERATED by docs/regen-packart.py from img/packs-art/ -- do not edit.
   Keyed by ArkhamDB pack code; each value is a tile cut to the pack
   card's proportion. Packs with no entry keep the star field. */
(function (global) {
  'use strict';

  var DIR = 'img/packs-art/';

  var TILES = {
    'dwlc': 'tiles/dwlc.webp',
    'dwlp': 'tiles/dwlp.webp',
    'eoep': 'tiles/eoep.webp',
    'rcore': 'tiles/rcore.webp',
  };

  /* Absolute, like GameIcons: the URL travels through a CSS custom
     property, and a relative one would resolve against the stylesheet
     that uses it (css/) instead of the page. */
  global.PackArt = {
    url: function (code) {
      var file = TILES[code];
      return file ? new URL(DIR + file, document.baseURI).href : null;
    }
  };
})(window);
